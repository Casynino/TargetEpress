// Builds lib/hero-map.ts: the coastlines from East Africa to China as one SVG
// path, and the cities on it, for the homepage hero. Run: node scripts/gen-hero-map.mjs
// Pre-computed because the answer never changes and the page should not do
// map projection work on a phone.
import { readFileSync, writeFileSync } from "node:fs";
import { geoEquirectangular, geoPath } from "d3-geo";

const W = 1000;
const H = 560;
const LON = [12, 128];
const LAT = [-30, 42];

const land = JSON.parse(readFileSync(new URL("../public/geo/land-110m.json", import.meta.url), "utf8"));
// d3 reads a ring clockwise as the inside; the other way round it is the rest of the world.
const projection = geoEquirectangular()
  .fitExtent([[0, 0], [W, H]], { type: "Feature", geometry: { type: "Polygon", coordinates: [[[LON[0], LAT[0]], [LON[0], LAT[1]], [LON[1], LAT[1]], [LON[1], LAT[0]], [LON[0], LAT[0]]]] } })
  .clipExtent([[-20, -20], [W + 20, H + 20]]);
const path = geoPath(projection).digits(1);

const d = land.features.map((f) => path(f) ?? "").filter(Boolean).join("");

const at = (lon, lat) => projection([lon, lat]).map((n) => Math.round(n * 10) / 10);
const CITIES = {
  dar: at(39.28, -6.79),
  guangzhou: at(113.26, 23.13),
  hongKong: at(114.17, 22.32),
  dubai: at(55.27, 25.2),
  addis: at(38.74, 8.98),
};
// Cities that light the night map. Real places, so the glow sits where people are.
const LIGHTS = [
  [121.47, 31.23], [116.4, 39.9], [104.07, 30.67], [108.94, 34.34], [120.15, 30.28], [117.2, 39.13],
  [100.5, 13.75], [106.7, 10.78], [105.85, 21.03], [101.69, 3.14], [103.82, 1.35], [106.85, -6.2],
  [72.88, 19.08], [77.21, 28.61], [88.36, 22.57], [80.27, 13.08], [77.59, 12.97], [67.0, 24.86], [74.35, 31.55],
  [90.41, 23.81], [96.16, 16.84], [51.53, 25.29], [46.68, 24.71], [39.83, 21.42], [44.37, 33.31], [51.39, 35.69],
  [31.24, 30.04], [32.53, 15.59], [36.82, -1.29], [32.58, 0.35], [29.36, -3.38], [39.67, -4.04], [28.04, -26.2],
  [31.03, -17.83], [33.79, -13.97], [28.32, -15.42], [43.24, -11.7], [47.52, -18.91], [45.34, 2.05], [42.59, 11.59],
].map(([lon, lat]) => at(lon, lat));

const out = `/**
 * The homepage hero's map: coastlines from East Africa to China as one SVG
 * path, with the route's cities and the night lights of the region's big
 * cities, all through one projection so everything lines up.
 *
 * Generated by scripts/gen-hero-map.mjs from public/geo/land-110m.json (the
 * same data the globe uses). Do not edit by hand — regenerate.
 *
 * Window: lon ${LON[0]}..${LON[1]}, lat ${LAT[0]}..${LAT[1]}, ${W}x${H}, equirectangular.
 */
export const HERO_MAP = { width: ${W}, height: ${H} } as const;
export const HERO_LAND = ${JSON.stringify(d)};
export const HERO_CITIES = ${JSON.stringify(CITIES)} as const;
export const HERO_LIGHTS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(LIGHTS)};
`;
writeFileSync(new URL("../lib/hero-map.ts", import.meta.url), out);
console.log("land path", d.length, "chars;", "cities", JSON.stringify(CITIES));
